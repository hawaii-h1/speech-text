# Writes SpeechText/SpeechText/Resources/ThirdPartyNotices.txt — the licences of the
# third-party code and material the app ships, which their licences require to travel
# with every copy. Settings › General › Acknowledgements opens it.
#
#   scripts/third-party-notices.sh
#
# Each package pinned in Package.resolved that is linked into the app gets its own
# LICENSE and every notice it carries for code of others inside it (WhisperKit's
# NOTICES, FluidAudio's ThirdPartyLicenses/), from the exact pinned checkout. Material
# that is not a package — a bundled model — is a hand-written section in
# scripts/notices/*.txt. Run it after changing a package: ThirdPartyNoticesTests fails
# while the file names a version Package.resolved no longer pins.
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
project="$repo/SpeechText/SpeechText.xcodeproj"
resolved="$project/project.xcworkspace/xcshareddata/swiftpm/Package.resolved"
out="$repo/SpeechText/SpeechText/Resources/ThirdPartyNotices.txt"
packages="${TMPDIR:-/tmp}/speechtext-notices-packages"

echo "▸ Resolving the pinned packages into ${packages}…"
xcodebuild -resolvePackageDependencies -project "$project" -scheme SpeechText \
  -clonedSourcePackagesDirPath "$packages" >/dev/null

version() { # identity → the version Package.resolved pins
  /usr/bin/python3 -c 'import json,sys; pins={p["identity"]:p["state"] for p in json.load(open(sys.argv[1]))["pins"]}; s=pins[sys.argv[2]]; print(s.get("version") or s["revision"][:12])' "$resolved" "$1"
}

section() { # title, then the text on stdin
  printf '\n\n%s\n%s\n\n' "$1" "$(printf '%*s' "${#1}" '' | tr ' ' '=')"
  cat
}

package() { # identity, display name, url, files relative to the checkout…
  local identity=$1 name=$2 url=$3; shift 3
  local dir="$packages/checkouts/$identity" v; v=$(version "$identity")
  {
    printf '%s %s — %s\n' "$identity" "$v" "$url"
    for file in "$@"; do
      for path in "$dir"/$file; do
        [ -f "$path" ] || { echo "missing $path" >&2; exit 1; }
        printf '\n--- %s ---\n\n' "${path#"$dir/"}"
        cat "$path"
      done
    done
  } | section "$name"
}

{
  cat <<'HEADER'
Third-party notices
===================

SpeechText is free software under the GNU General Public License, version 3 or later.
It ships the third-party code and material below, each under its own licence, whose
text follows. This file is generated by scripts/third-party-notices.sh from the
packages pinned in Package.resolved; swift-argument-parser, which one of them pulls
in, is not linked into the app and is not listed.
HEADER
  package argmax-oss-swift "WhisperKit" "https://github.com/argmaxinc/argmax-oss-swift" LICENSE NOTICES
  package fluidaudio "FluidAudio" "https://github.com/FluidInference/FluidAudio" LICENSE "ThirdPartyLicenses/*"
  package sparkle "Sparkle" "https://github.com/sparkle-project/Sparkle" LICENSE
  for notice in "$repo"/scripts/notices/*.txt; do
    [ -f "$notice" ] || continue
    title=$(head -1 "$notice")
    tail -n +2 "$notice" | section "$title"
  done
} > "$out"

echo "Wrote ${out#"$repo/"} ($(wc -l < "$out" | tr -d ' ') lines)"
